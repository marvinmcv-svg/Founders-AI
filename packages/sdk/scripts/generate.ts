/**
 * Regenerates src/schema.ts (typed paths + parameters) from the live API definition, so the SDK
 * cannot drift from the server: `pnpm --filter @founders/sdk generate`. A test fails if it is stale.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import "@founders/api";
import { openApiDocument } from "../../../apps/api/src/kit";

export const SPEC_SERVER = "https://api.example.invalid/api/v1";

export async function renderSchema(): Promise<string> {
  const doc = openApiDocument(SPEC_SERVER) as unknown as Parameters<typeof openapiTS>[0];
  const ast = await openapiTS(doc, { alphabetize: true });
  return `/** Generated by scripts/generate.ts from the Founders AI OpenAPI document. Do not edit. */\n\n${astToString(ast)}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = path.join(path.dirname(fileURLToPath(import.meta.url)), "../src/schema.ts");
  writeFileSync(out, await renderSchema());
  console.log(`wrote ${out}`);
}
